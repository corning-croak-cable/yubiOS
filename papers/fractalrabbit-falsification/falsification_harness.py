"""
Falsification harness for curve-rsi / single-action-curve-rsi pipeline using
a synthetic stochastic corpus generated by the fractalrabbit-inspired
simulator (fractalrabbit_sim.py).

Four falsification tests, each with a clear pass/fail signal:

  Test 1 — Basic fit quality:
    Generate N=300 synthetic observations, fit curve, check
    PC1+PC2 ≥ 0.40 (the single-action-curve-rsi §Pre-Fit Validation gate).

  Test 2 — Sparse-cell recovery on planted anomalies:
    Inject K=10 synthetic items with KNOWN rare 9-D primitive combinations
    (planting rule: combinations that never appear in the natural distribution).
    Fit curve on the augmented corpus; detect sparse cells; check that
    ≥80% of planted items end up in cells flagged as sparse.

  Test 3 — Geodesic-only invariant (Lemma 1):
    Run the atom on every item; check that Δ ≥ 0 for every geodesic winner
    (no negative Δ — the core invariant of the atom).

  Test 4 — End-to-end falsification signal:
    Print a single PASS/FAIL verdict that combines Tests 1–3.

The harness writes a JSON results file at
session/fractalrabbit-falsification/results.json for downstream inspection.
"""
from __future__ import annotations
import json
import os
import sys
import time
from pathlib import Path

import numpy as np

# local imports — assume the harness runs from the same directory
HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))

from fractalrabbit_sim import simulate  # noqa: E402
from curve_fit_pipeline import (  # noqa: E402
    PRIMITIVE_NAMES, N_PRIMITIVES, build_corpus, fit_curve, SparseCellGrid,
    ideal_pole, atom_single_action, chordal_distance,
)


# ---------------------------------------------------------------------------
# Test 1 — basic fit quality
# ---------------------------------------------------------------------------
def test_basic_fit(C: np.ndarray, label: str) -> dict:
    fit = fit_curve(C)
    pc1, pc2 = fit["pc1_pc2_variance"]
    passed = (pc1 + pc2) >= 0.40
    return {
        "test": "basic_fit",
        "label": label,
        "n_items": int(C.shape[0]),
        "n_primitives_kept": int(C.shape[1] - len(fit["dropped_columns"])),
        "primitives_dropped": [PRIMITIVE_NAMES[i] for i in fit["dropped_columns"]],
        "pc1": pc1,
        "pc2": pc2,
        "pc1_pc2": pc1 + pc2,
        "threshold": 0.40,
        "passed": passed,
    }


# ---------------------------------------------------------------------------
# Test 2 — planted anomalies land in sparse cells
# ---------------------------------------------------------------------------
# 10 distinct rare 9-D combinations. Each combination is engineered to be
# probabilistically rare in the natural simulator output (each hits 1–2
# primitives that are unlikely to all co-occur in the same observation).
# The combinations are designed so that if any ONE of them lands in a sparse
# cell, the rest are likely to as well — i.e., we want to test the detector's
# sensitivity to STRUCTURAL rarity, not to a single outlier.
PLANT_COMBINATIONS = [
    np.array([1, 0, 0, 0, 0, 0, 0, 0, 1], dtype=np.int8),  # burst + late
    np.array([0, 1, 0, 0, 0, 0, 0, 0, 1], dtype=np.int8),  # recurrent + late
    np.array([0, 0, 1, 1, 0, 0, 0, 0, 0], dtype=np.int8),  # first visit + fract limit
    np.array([0, 0, 0, 0, 1, 0, 0, 0, 1], dtype=np.int8),  # long gap + late
    np.array([0, 0, 0, 0, 0, 1, 1, 0, 0], dtype=np.int8),  # short gap + origin
    np.array([0, 0, 0, 1, 0, 0, 0, 1, 0], dtype=np.int8),  # fract + cross cluster
    np.array([1, 0, 0, 0, 0, 0, 0, 1, 0], dtype=np.int8),  # burst + cross cluster
    np.array([0, 1, 0, 0, 1, 0, 0, 0, 0], dtype=np.int8),  # recurrent + long gap
    np.array([0, 0, 1, 0, 0, 0, 1, 0, 1], dtype=np.int8),  # first + origin + late
    np.array([0, 0, 0, 1, 0, 0, 0, 0, 0], dtype=np.int8),  # fract limit only
]


def test_sparse_cell_recovery(
    C_natural: np.ndarray, label: str, rng_seed: int = 7,
) -> dict:
    """
    Inject K=10 planted items, refit curve, check sparse-cell detection.
    """
    rng = np.random.default_rng(rng_seed)
    # plant items
    C_augmented = np.vstack([C_natural, np.stack(PLANT_COMBINATIONS)])
    plant_indices = list(range(C_natural.shape[0], C_augmented.shape[0]))

    fit = fit_curve(C_augmented)
    grid = SparseCellGrid.from_fit(fit["uv"])

    # for each planted item, check what cell it landed in
    recovered = 0
    cell_records = []
    for plant_idx, plant_idx_in_aug in enumerate(plant_indices):
        u, v = fit["uv"][plant_idx_in_aug]
        i, j = grid.cell_of(u, v)
        cell = grid.cells.get((i, j), [])
        # sparse = cell has only 1 item (the planted one) or 0 items
        is_sparse = len(cell) <= 1
        if is_sparse:
            recovered += 1
        cell_records.append({
            "plant_combo": PLANT_COMBINATIONS[plant_idx].tolist(),
            "u": float(u),
            "v": float(v),
            "cell": (i, j),
            "cell_size": len(cell),
            "in_sparse_cell": bool(is_sparse),
        })

    recovery_rate = recovered / len(PLANT_COMBINATIONS)
    passed = recovery_rate >= 0.80

    return {
        "test": "sparse_cell_recovery",
        "label": label,
        "n_natural": int(C_natural.shape[0]),
        "n_planted": len(PLANT_COMBINATIONS),
        "n_recovered": int(recovered),
        "recovery_rate": float(recovery_rate),
        "threshold": 0.80,
        "passed": bool(passed),
        "per_plant_record": cell_records,
    }


# ---------------------------------------------------------------------------
# Test 3 — Lemma 1 (no negative Δ)
# ---------------------------------------------------------------------------
def test_lemma_1(C: np.ndarray, label: str) -> dict:
    """
    For each item in the corpus, run the atom and verify Δ ≥ 0.
    Per single-action-curve-rsi SKILL.md Lemma 1: the geodesic-only criterion
    can never produce Δ < 0; either Δ > 0 (improvement) or Δ = 0 (local min).
    """
    fit = fit_curve(C)
    pstar = ideal_pole(C)

    n_total = 0
    n_strict_positive = 0
    n_zero = 0
    n_violations = 0  # Δ < 0 — should be 0

    for idx in range(C.shape[0]):
        result = atom_single_action(C[idx], pstar, fit)
        delta = result["delta"]
        n_total += 1
        if delta > 1e-9:
            n_strict_positive += 1
        elif abs(delta) <= 1e-9:
            n_zero += 1
        else:
            n_violations += 1

    passed = (n_violations == 0)
    return {
        "test": "lemma_1_invariant",
        "label": label,
        "n_items": int(n_total),
        "n_delta_positive": int(n_strict_positive),
        "n_delta_zero": int(n_zero),
        "n_delta_negative_violations": int(n_violations),
        "passed": bool(passed),
    }


# ---------------------------------------------------------------------------
# Orchestrator
# ---------------------------------------------------------------------------
def run_harness(
    n_sites: int = 80,
    n_steps: int = 2000,
    seed: int = 42,
    verbose: bool = True,
) -> dict:
    t_start = time.time()

    if verbose:
        print(f"[harness] simulating fractalrabbit: n_sites={n_sites} "
              f"n_steps={n_steps} seed={seed}")

    sim = simulate(
        n_sites=n_sites, n_steps=n_steps, seed=seed,
        alpha=0.10, beta=1.5, burst_prob=0.6,
        heavy_tail_alpha=1.5, agp_min_distance=0.04,
    )

    if verbose:
        print(f"[harness] simulator: {len(sim.observations)} observations, "
              f"{sim.n_sites} sites, {sim.n_steps} steps; "
              f"inter-event gap median = "
              f"{int(np.median(sim.inter_event_times)) if sim.inter_event_times else 'NA'}")

    C, meta = build_corpus(sim)
    if verbose:
        print(f"[harness] corpus: shape {C.shape}, "
              f"per-column coverage: {C.mean(axis=0).round(3).tolist()}")

    # Test 1: basic fit
    t1 = test_basic_fit(C, "natural-corpus")
    if verbose:
        print(f"[harness] Test 1 (basic fit): PC1+PC2 = {t1['pc1_pc2']:.4f}, "
              f"passed = {t1['passed']}")

    # Test 2: sparse-cell recovery
    t2 = test_sparse_cell_recovery(C, "natural-corpus-with-planted-anomalies")
    if verbose:
        print(f"[harness] Test 2 (sparse-cell recovery): "
              f"recovered {t2['n_recovered']}/{t2['n_planted']} planted "
              f"({t2['recovery_rate']:.0%}), passed = {t2['passed']}")

    # Test 3: Lemma 1 invariant
    t3 = test_lemma_1(C, "natural-corpus")
    if verbose:
        print(f"[harness] Test 3 (Lemma 1 invariant): "
              f"Δ>0 = {t3['n_delta_positive']}, "
              f"Δ=0 = {t3['n_delta_zero']}, "
              f"Δ<0 violations = {t3['n_delta_negative_violations']}, "
              f"passed = {t3['passed']}")

    overall_passed = bool(t1["passed"] and t2["passed"] and t3["passed"])

    elapsed = time.time() - t_start
    results = {
        "harness_version": "0.1.0",
        "simulator_params": {
            "n_sites": n_sites, "n_steps": n_steps, "seed": seed,
            "alpha": 0.10, "beta": 1.5, "burst_prob": 0.6,
            "heavy_tail_alpha": 1.5, "agp_min_distance": 0.04,
        },
        "corpus_stats": {
            "n_observations": int(C.shape[0]),
            "n_primitives_kept": int(t1["n_primitives_kept"]),
            "per_column_coverage": C.mean(axis=0).tolist(),
            "inter_event_gap_median": int(np.median(sim.inter_event_times)) if sim.inter_event_times else 0,
            "burst_observations": sim.n_burst_observations,
            "quiet_observations": sim.n_quiet_observations,
        },
        "tests": {
            "test_1_basic_fit": t1,
            "test_2_sparse_cell_recovery": t2,
            "test_3_lemma_1_invariant": t3,
        },
        "overall_passed": overall_passed,
        "elapsed_seconds": round(elapsed, 3),
    }

    if verbose:
        print(f"[harness] OVERALL: {'PASS' if overall_passed else 'FAIL'} "
              f"(elapsed {elapsed:.2f}s)")

    return results


def main():
    results = run_harness()
    out_path = HERE / "results.json"
    with open(out_path, "w") as f:
        json.dump(results, f, indent=2, default=str)
    print(f"[harness] wrote {out_path}")
    return 0 if results["overall_passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
